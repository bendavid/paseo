// Bundles the pdf.js viewer into a single self-contained HTML document, the
// same way build-terminal-webview-html.mjs does for xterm. The app never
// imports pdfjs-dist through Metro: pdf.js relies on `import.meta.url` and
// emits ES modules, both of which esbuild resolves here at build time.
//
// The legacy build is deliberate — it targets the same older Safari/WebView
// baseline as the terminal bundle (ios15).
import esbuild from "esbuild";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(appRoot, "../..");
const entry = path.join(appRoot, "src/pdf/webview/pdf-viewer-webview-entry.ts");
const output = path.join(appRoot, "src/pdf/webview/pdf-viewer-webview-html.ts");

const pdfjsRoot = path.dirname(require.resolve("pdfjs-dist/package.json"));
const pdfjsLegacyMain = path.join(pdfjsRoot, "legacy/build/pdf.min.mjs");
const pdfjsLegacyWorker = path.join(pdfjsRoot, "legacy/build/pdf.worker.min.mjs");

const buildTarget = ["ios15", "chrome100"];

async function resolveTsPath(basePath) {
  const candidates = [
    basePath,
    `${basePath}.ts`,
    `${basePath}.tsx`,
    path.join(basePath, "index.ts"),
  ];
  for (const candidate of candidates) {
    try {
      const stat = await fs.stat(candidate);
      if (stat.isFile()) return candidate;
    } catch {
      // try next candidate
    }
  }
  return basePath;
}

const aliasPlugin = {
  name: "paseo-pdf-alias",
  setup(build) {
    build.onResolve({ filter: /^@\// }, async (args) => ({
      path: await resolveTsPath(path.join(appRoot, "src", args.path.slice(2))),
    }));
    // TypeScript reads the package's own types; the runtime gets the legacy
    // build, which is compiled for the older WebView baseline.
    build.onResolve({ filter: /^pdfjs-dist$/ }, () => ({ path: pdfjsLegacyMain }));
  },
};

// `import.meta.url` only appears in pdf.js's optional-asset lookups (wasm,
// cmaps, standard fonts). Those files are not shipped inside the bundle, so
// the lookups resolve against the document and fail closed — pdf.js falls back
// to its pure-JS decoders and to system fonts.
const importMetaUrlShim = "self.location.href";

const workerBundle = await esbuild.build({
  entryPoints: [pdfjsLegacyWorker],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: buildTarget,
  minify: true,
  define: { "import.meta.url": importMetaUrlShim },
  logLevel: "warning",
});

const workerSource = workerBundle.outputFiles[0]?.text;
if (!workerSource) {
  throw new Error("pdf.js worker bundle produced no JavaScript");
}

const viewerBundle = await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: buildTarget,
  minify: true,
  define: {
    "import.meta.url": importMetaUrlShim,
    // Base64 keeps the payload ASCII. Embedded as a source string, pdf.js's
    // non-ASCII characters would each cost a six-byte \\uXXXX escape.
    __PDF_WORKER_SOURCE_BASE64__: JSON.stringify(
      Buffer.from(workerSource, "utf8").toString("base64"),
    ),
  },
  plugins: [aliasPlugin],
  logLevel: "warning",
});

const js = viewerBundle.outputFiles[0]?.text;
if (!js) {
  throw new Error("pdf viewer bundle produced no JavaScript");
}

const html = `<!doctype html>
<html>
  <head>
    <meta charset="utf-8" />
    <meta
      name="viewport"
      content="width=device-width, initial-scale=1, viewport-fit=cover"
    />
  </head>
  <body>
    <script>${js.replace(/<\/script/gi, "<\\/script")}</script>
  </body>
</html>`;

const contents = `// Generated by packages/app/scripts/build-pdf-webview-html.mjs.
// Do not edit by hand.

export const pdfViewerWebViewHtml = ${JSON.stringify(html)};
`;

await fs.writeFile(output, contents);
console.log(`Wrote ${path.relative(repoRoot, output)} (${html.length} bytes)`);
